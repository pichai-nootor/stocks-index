import { vipHotPick, vipDrill, VIP_MIN_HISTORY } from "./vip";
import { DIGITS10, resultDigits, type MarketFormula, type VipDraw, type VipPick } from "./types";

/** ถ่วงดุลนับย้อนกี่วัน (ตอนนี้ประวัติยังไม่ถึง จึงเท่ากับนับทั้งหมด) */
const IN_FREQ_WINDOW = 100;

/**
 * ทดลอง — ถ่วงดุลของอินเดียเอง: ตัดเลขที่ออกเมื่อวาน แล้วเรียงเลขที่ออกน้อยสุดใน IN_FREQ_WINDOW วัน (เสมอกัน → เลขน้อยก่อน)
 */
export function inBalancePick(history: VipDraw[]): VipPick | null {
  if (history.length < VIP_MIN_HISTORY) return null;
  const sets = history.slice(-IN_FREQ_WINDOW).map((h) => new Set(resultDigits(h.top, h.bottom)));
  const prev = sets[sets.length - 1];
  const count = (d: string) => sets.filter((x) => x.has(d)).length;
  const order = [...DIGITS10].sort((a, b) => (+prev.has(a) - +prev.has(b)) || count(a) - count(b) || a.localeCompare(b));
  const why = (d: string) => `${d} (ออก ${count(d)}/${sets.length} วัน${prev.has(d) ? " · ออกเมื่อวาน" : ""})`;
  return {
    formula: "in-balance", label: "ถ่วงดุลของอินเดีย", digits: [order[0], order[1]], order,
    note: `ตัดเลขที่ออกเมื่อวาน (${[...prev].sort().join(" ")}) แล้วเลือกเลขที่ออกน้อยสุด: ${why(order[0])}, ${why(order[1])} · อันดับถัดไป ${order.slice(2, 5).join(", ")} · ฟันย้อนหลัง 31 วันของอินเดีย ★ 45.5% · 2 ตัว 75.8% แต่ติดเลข 8 เกือบทุกวัน — งวดยังน้อย`,
  };
}

/**
 * แผน C — ใช้ผล "หุ้นอินเดียปกติ (BSE SENSEX)" ของวันเดียวกันมาฟัน VIP
 *   SENSEX ปกติออก 17:00 ไทย · อินเดีย VIP ออก 17:25 → รู้ผลปกติก่อน 25 นาที เอามาใช้ทัน
 *   หลักฐาน 12 วันที่ทับกัน (4–22 ก.ย. 69): เอา 2 ตัวบนของปกติไปฟัน VIP เข้า 83.3% · 2 ตัวล่างของปกติ 83.3% · สุ่ม 2 ตัว 58.5%
 *   แยกตามตำแหน่งของเลขปกติที่ไปโผล่ใน VIP: ล่างหน่วย 67% · บนสิบ 50% · บนหน่วย 42% · ล่างสิบ 25% (เส้นสุ่มต่อตัว ~37%)
 *   → แผน C เลือก "ล่างหน่วย + บนสิบ" ของผลปกติ
 *   ⚠ 12 วันมีความคลาดเคลื่อน ±21 จุด — ยังไม่ใช่สูตรหลัก เก็บคะแนนคู่กันไปก่อน
 */
export function inPlanC(regular: { top: string; bottom: string } | null | undefined): VipPick | null {
  if (!regular?.top || !regular?.bottom) return null;
  const t = regular.top.slice(-2), b = regular.bottom;
  const a = b[1], c = t[0];                       // ล่างหน่วย (67%) + บนสิบ (50%)
  const digits: [string, string] = a === c ? [a, t[1]] : [a, c];
  return { formula: "in-planC", label: "แผน C (จากหุ้นอินเดียปกติ)", digits, note: `ผลปกติวันนี้ ${t}/${b} → หยิบ ล่างหน่วย ${b[1]} + บนสิบ ${t[0]}${a === c ? ` (ซ้ำกัน จึงใช้ บนหน่วย ${t[1]} แทน)` : ""}` };
}

