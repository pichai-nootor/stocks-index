/**
 * โอกาสปิดขึ้นของอียิปต์วันถัดไป จากประวัติ "ก่อนวันนั้น" เท่านั้น (ไม่มองอนาคต) ผสมฐาน 0.5 น้ำหนัก 30 วัน
 * ใช้แทนทิศทางจากราคาเปิด เพราะอียิปต์ไม่มีราคาเปิดจริง — ของอียิปต์เท่านั้น
 */
export function egyptPUp(history: { closeChange: number | null }[]): number {
  const ch = history.map((r) => r.closeChange).filter((c): c is number => c !== null);
  if (ch.length < 2) return 0.5;
  const prevUp = ch[ch.length - 1] > 0;
  let n = 0, up = 0;
  for (let i = 1; i < ch.length; i++) if (ch[i - 1] > 0 === prevUp) { n++; if (ch[i] > 0) up++; }
  return (0.5 * 30 + up) / (30 + n);
}

