/** ย้อนดูกี่งวดตอนไล่หา "คู่ที่ฟันเมื่อวาน" (กฎห้ามคู่เดิมขึ้นกับวันก่อน → ไล่จากจุดนี้มาถึงวันนี้) */
const DE_CHAIN = 40;

/** อันดับเลขของงวดที่ j (ใช้ผล 0..j−1): เลขที่ออกน้อยรวม 45/50/55 งวด (เสมอ → เลขมาก) แล้วเลขที่หายเกิน 5 งวดไปท้าย */
function rankAt(sets: Set<string>[], j: number) {
  const counts = Object.fromEntries(DIGITS10.map((d) => [d, DE_WINDOWS.map((w) => { let c = 0; for (let i = Math.max(0, j - w); i < j; i++) if (sets[i].has(d)) c++; return c; })])) as Record<string, number[]>;
  const score = (d: string) => DE_WINDOWS.reduce((s, w, k) => s + counts[d][k] / w, 0);
  const gap = (d: string) => { let k = 0; for (let i = j - 1; i >= 0 && !sets[i].has(d); i--) k++; return k; };
  const cold = [...DIGITS10].sort((a, b) => score(a) - score(b) || Number(b) - Number(a));
  const away = (d: string) => gap(d) > DE_MAX_GAP;
  return { order: [...cold.filter((d) => !away(d)), ...cold.filter(away)], counts, skipped: cold.filter(away).map((d) => `${d} (หาย ${gap(d)} งวด)`) };
}
const samePair = (a: string[], b: string[]) => canon2(a.join("")) === canon2(b.join(""));

function pickDe(history: VipDraw[]): VipPick | null {
  if (history.length < DE_MIN_HISTORY) return null;
  const sets = history.map((h) => new Set(resultDigits(h.top, h.bottom)));
  // ห้ามฟันคู่เดิมซ้ำเมื่อวาน: อันดับ 1+2 ซ้ำคู่ของวันก่อน → ใช้อันดับ 1+3 · ไล่ตั้งแต่ DE_CHAIN งวดก่อนเพื่อรู้ว่าเมื่อวานฟันคู่ไหน
  let prev: string[] | null = null, last: ReturnType<typeof rankAt> | null = null, switched = false;
  for (let j = Math.max(DE_MIN_HISTORY, sets.length - DE_CHAIN); j <= sets.length; j++) {
    const r = rankAt(sets, j);
    let p = [r.order[0], r.order[1]];
    const sw = !!prev && samePair(p, prev);
    if (sw) p = [r.order[0], r.order[2]];
    if (j === sets.length) { last = r; switched = sw; }
    prev = p;
  }
  const { order, counts, skipped } = last!;
  const digits = prev as [string, string];
  const why = (d: string) => `${d} (ออก ${DE_WINDOWS.map((w, k) => `${counts[d][k]}/${w}`).join(" · ")})`;
  const pct = (x: number) => `${(100 * x).toFixed(1)}%`;
  return {
    order: [...digits, ...order.filter((d) => !digits.includes(d))], formula: "de-cold-gap-norepeat", label: "สูตรเยอรมัน VIP", digits,
    note: `เลขที่ออกน้อย (รวม ${DE_WINDOWS.join("/")} งวด): ${why(digits[0])}, ${why(digits[1])}${switched ? ` · เลี่ยงคู่เดิมของเมื่อวาน (${order[0]}-${order[1]}) → ใช้อันดับ 1 + 3` : ""} · อันดับถัดไป ${order.filter((d) => !digits.includes(d)).slice(0, 3).join(", ")}${skipped.length ? ` · ข้ามเลขที่หายเกิน ${DE_MAX_GAP} งวด: ${skipped.join(", ")}` : ""} · ทดสอบ 1,401 งวด เจาะเข้า ${pct(DE_BASE.drill)} (สุ่ม ${pct(DE_BASE.randomDrill)}) · 2 ตัว ${pct(DE_BASE.any)}`,
  };
}

/** เลขเจาะ: เลขที่ฟัน + เลขที่ออกล่าสุด (หายน้อยงวดสุดมาก่อน · เสมอ → เลขน้อย) ตัดเบิ้ล ไม่ซ้ำคู่ข้ามชุด ชุดละ 6 */
function drillDe(pick: VipPick, history: VipDraw[]): VipDrillSet[] {
  const sets = history.map((h) => new Set(resultDigits(h.top, h.bottom)));
  const gap = (d: string) => { let k = 0; for (let i = sets.length - 1; i >= 0 && !sets[i].has(d); i--) k++; return k; };
  const g = Object.fromEntries(DIGITS10.map((d) => [d, gap(d)])) as Record<string, number>;
  const row = (d: string, taken: string[]) => DIGITS10.filter((x) => x !== d && !taken.includes(canon2(d + x)))
    .sort((x, y) => g[x] - g[y] || x.localeCompare(y))
    .slice(0, DE_DRILL_PER_DIGIT).map((x) => d + x);
  const [a, b] = pick.digits;
  const rowA = row(a, []);
  const rowB = row(b, rowA.map(canon2));
  return [{ digit: a, numbers: rowA }, { digit: b, numbers: rowB }];
}

