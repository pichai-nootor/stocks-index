import { DIGITS10, resultDigits, canon2, type MarketFormula, type VipDraw, type VipPick, type VipDrillSet } from "./types";

export const DE_MIN_HISTORY = 55;
const DE_WINDOWS = [45, 50, 55] as const;
const DE_DRILL_PER_DIGIT = 6;
/** เลขที่หายเกินกี่งวดติดให้ลดไปท้ายอันดับ (ระบบกำลังกดเลขนั้น) */
const DE_MAX_GAP = 5;
/** walk-forward งวด 320 → ด้วยไฟล์นี้ (ข้ามเลขหาย + ห้ามคู่เดิม + เจาะคู่เลขที่ออกล่าสุด) · เงิน +275,520 ทรุด −43,840 (เลขละ 20) */
